function _rng(seed) { return () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
function tile(w, h, scale, draw, seed = 7) {
  const c = document.createElement('canvas'); c.width = w; c.height = h; draw(c.getContext('2d'), _rng(seed));
  const o = document.createElement('canvas'); o.width = w * scale; o.height = h * scale;
  const g = o.getContext('2d'); g.imageSmoothingEnabled = false; g.drawImage(c, 0, 0, o.width, o.height);
  return `url(${o.toDataURL()})`;
}
