function palette(name, shades, lvl, gem, extra) {
  const [l, m, d] = shades.length === 3 ? shades : NEUTRAL;
  const pal = { ...BASE_PAL, ...(ACCENT[name] || {}), h: mixc(l, '#ffffff', .55), l, m, d, e: mixc(d, INK, .42), o: LV_INK[lvl] || mixc(d, INK, .8) };
  // Molde (sem minério): os detalhes coloridos ficam acinzentados, como uma peça ainda sem acabamento
  if (isMold(shades) && ACCENT[name] && !name.startsWith('i_')) for (const k in ACCENT[name]) pal[k] = gray(pal[k], .8);
  const tr = TRIM[lvl];
  pal.t = tr ? tr[0] : pal.d; pal.T = tr ? tr[1] : pal.e; pal.v = tr ? tr[0] : pal.m;
  pal.u = tr ? pal.p : pal.m; pal.U = tr ? pal.P : pal.d;   // empunhadura: madeira simples no nível 1
  const jw = gem ? [gem, mixc(gem, '#ffffff', .55)] : JEWEL[lvl];
  pal.k = jw ? jw[0] : pal.m; pal.K = jw ? jw[1] : pal.l;
  if (extra) { Object.assign(pal, extra); if (extra.b) pal.B = mixc(extra.b, '#ffffff', .3); }
  return pal;
}

/* Desenha o sprite num canvas e devolve uma imagem (data URL), com cache */
const _sprCache = new Map();
function sprite(name, shades = NEUTRAL, scale = 4, lvl = 1, gem = null, extra = null) {
  if (gem && SPR[name + '_g']) name += '_g';   // anel, amuleto e cajado têm um desenho próprio com a gema
  const key = name + shades.join() + isMold(shades) + scale + '/' + lvl + '/' + gem + '/' + (extra ? JSON.stringify(extra) : '');
  if (_sprCache.has(key)) return _sprCache.get(key);
  const cv = spriteCanvas(name, shades, scale, lvl, gem, extra);
  const url = cv.toDataURL(); _sprCache.set(key, url); return url;
}
function spriteCanvas(name, shades = NEUTRAL, scale = 1, lvl = 1, gem = null, extra = null) {
  const rows = SPR[name], w = Math.max(...rows.map(r => r.length)), h = rows.length;
  const pal = palette(name.replace(/_g$/, ''), shades, lvl, gem, extra);
  const cv = document.createElement('canvas'); cv.width = w * scale; cv.height = h * scale;
  const g = cv.getContext('2d');
  rows.forEach((r, y) => [...r].forEach((ch, x) => { if (pal[ch]) { g.fillStyle = pal[ch]; g.fillRect(x * scale, y * scale, scale, scale); } }));
  return cv;
}
